// module's Vite plugin and the wrapper run as written (bundled with a stand-in nuxt/kit, Vue and
// useRequestURL), the generated list and registry, and the setup planned for a mapped repo alone
// (ground rule 2). The swap in a real page is the conformance suite's (the nuxt fixture).
