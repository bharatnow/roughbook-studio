const nuxt = recipeFor('nuxt')!;
const LINK = { version: 1 as const, orgId: 'org-1', project: 'site', roughCommitted: true };

const write = (repo: string, file: string, text: string) => {
  fs.mkdirSync(path.dirname(path.join(repo, ...file.split('/'))), { recursive: true });
  fs.writeFileSync(path.join(repo, ...file.split('/')), text);
};
const read = (repo: string, file: string) =>
  fs.readFileSync(path.join(repo, ...file.split('/')), 'utf8');

const page = (slug: string, address: string | null, sections: string[]): MapPage => ({
  slug,
  name: slug,
  address,
  example: null,
  signIn: 'no',
  files: [],
  sections,
  byAgent: false
});
const component = (slug: string, file: string): MapComponent => ({
  slug,
  name: slug,
  kind: 'section',
  files: [file],
  export: 'default',
  fixture: null,
  alone: 'unknown',
  why: null,
  byAgent: false
});

/** A mapped Nuxt app with its pricing plans adopted on two pages and one fork of them. */
async function nuxtRepo(): Promise<string> {
  const repo = await tempDir('roughbook-context-nuxt-');
  writeMap(repo, {
    version: 1,
    by: ['nuxt'],
    pages: [page('pricing', '/pricing', ['plans', 'faq']), page('home', '/', ['plans'])],
    components: [
      component('plans', 'app/components/pricing/Plans.vue'),
      component('faq', 'app/components/pricing/Faq.vue')
    ],
    missed: [],
    unplaced: []
  });
  write(repo, 'nuxt.config.ts', 'export default defineNuxtConfig({});\n');
  write(repo, 'app/app.vue', '<template><NuxtPage /></template>\n');
  for (const key of [
    'pricing/plans/iteration-00',
    'pricing/plans/iteration-01',
    'home/plans/iteration-00'
  ]) {
    write(repo, `rough/${key}/index.vue`, '<template><p>x</p></template>\n');
  }
  return repo;
}

describe('the Nuxt switch, planned', () => {
  it('is planned with its module and wrapper for a mapped repo only, edits nothing of the app’s, and is listed for doctor and uninstall', async () => {
    assert.ok(nuxt.version >= 2);
    const repo = await nuxtRepo();
    const link = { ...LINK, appDir: null };
    const hook = nuxt.contextPreview!;
    assert.deepEqual(hook.missing(repo, link), [CONTEXT_MODULE, CONTEXT_SECTION]);
    const plan = planPrep(repo, { link: LINK, recipe: nuxt });
    const files = plan.changes.map(change => change.file);
    assert.ok(files.includes(CONTEXT_MODULE) && files.includes(CONTEXT_SECTION));
    assert.ok(!plan.changes.some(change => change.action === 'edit'));
    for (const file of [CONTEXT_MODULE, CONTEXT_SECTION]) {
      assert.ok(nuxt.setupFiles(repo, link).includes(file), file);
    }
    assert.deepEqual(hook.edits(repo, link), []);
    assert.ok(nuxt.generatedFiles.includes(CONTEXT_MODULES));
    assert.ok(nuxt.generatedFiles.includes(CONTEXT_REGISTRY));
    assert.equal(hook.sentinel, CONTEXT_SENTINEL);
    assert.ok(!hook.browser);
    assert.equal(
      hook.address('/pricing', 'pricing/plans/iteration-01', { pick: true }),
      '/pricing?roughbook-swap=pricing/plans/iteration-01&roughbook-pick=1'
    );

    // Applied, as init and setup --upgrade apply it: the list and the registry come with it.
    applyPrep(plan);
    assert.deepEqual(hook.missing(repo, link), []);
    assert.deepEqual(JSON.parse(read(repo, CONTEXT_MODULES)), {
      'app/components/pricing/Plans.vue': {
        export: 'default',
        sections: [
          { key: 'pricing/plans', address: '/pricing' },
          { key: 'home/plans', address: '/' }
        ]
      }
    });
    assert.equal(
      read(repo, CONTEXT_REGISTRY),
      `// Generated by Roughbook from the adopted components in this folder, for the in-page view. Do not edit.
/** The iterations a page can show in a component's place, loaded only when a page asks for one. */
export const loaders: Record<string, () => Promise<unknown>> = {
  "pricing/plans/iteration-01": () => import("./pricing/plans/iteration-01/index.vue"),
};
`
    );
    const gitignore = read(repo, '.gitignore');
    for (const file of [CONTEXT_MODULE, CONTEXT_SECTION, CONTEXT_MODULES, CONTEXT_REGISTRY]) {
      assert.ok(gitignore.includes(`/${file}`), file);
    }

    const plain = await tempDir('roughbook-context-nuxt-');
    write(plain, 'nuxt.config.ts', 'export default defineNuxtConfig({});\n');
    const before = planPrep(plain, { link: LINK, recipe: nuxt }).changes.map(change => change.file);
    assert.ok(!before.includes(CONTEXT_MODULE));
    assert.deepEqual(nuxt.setupFiles(plain, link), ['modules/rough-preview.ts']);
    nuxt.syncPreview(plain);
    assert.ok(!fs.existsSync(path.join(plain, CONTEXT_MODULES)));
  });

  it('every file of the switch holds the gate’s sentinel', () => {
    for (const item of contextFiles())
      assert.ok(item.content.includes(CONTEXT_SENTINEL), item.file);
  });
});

/** Bundles one of the switch's files with stand-ins for what it imports, and imports it. */
async function bundled<T>(repo: string, file: string, stand: Record<string, string>): Promise<T> {
  const alias: Record<string, string> = {};
  for (const [name, text] of Object.entries(stand)) {
    const at = `stand-ins/${name.replace(/[^a-z]+/gi, '-')}.js`;
    write(repo, at, text);
    alias[name] = path.join(repo, ...at.split('/'));
  }
  const out = path.join(repo, `bundle-${Math.random().toString(36).slice(2)}.mjs`);
  buildSync({
    entryPoints: [path.join(repo, ...file.split('/'))],
    bundle: true,
    format: 'esm',
    platform: 'node',
    outfile: out,
    logLevel: 'silent',
    define: { 'import.meta.dev': 'true' },
    alias
  });
  return (await import(pathToFileURL(out).href)) as T;
}

type VitePlugin = {
  name: string;
  enforce: string;
  resolveId(
    this: { resolve(source: string, importer: string): Promise<{ id: string } | null> },
    source: string,
    importer?: string,
    options?: object
  ): Promise<string | null>;
  load(id: string): string | null;
};

describe('the module', () => {
  const KIT = `export function defineNuxtModule(definition) { return definition; }
export function addVitePlugin(plugin) { (globalThis.roughbookPlugins ??= []).push(plugin); }
`;

  async function plugin(repo: string, dev = true): Promise<VitePlugin | undefined> {
    for (const item of contextFiles()) write(repo, item.file, item.content);
    write(
      repo,
      CONTEXT_MODULES,
      JSON.stringify({
        'app/components/pricing/Plans.vue': {
          export: 'default',
          sections: [{ key: 'pricing/plans', address: '/pricing' }]
        }
      })
    );
    const made = await bundled<{
      default: { setup(options: object, nuxt: object): void };
    }>(repo, CONTEXT_MODULE, { 'nuxt/kit': KIT });
    const globals = globalThis as Record<string, unknown>;
    globals.roughbookPlugins = [];
    made.default.setup({}, { options: { dev, rootDir: repo } });
    return (globals.roughbookPlugins as VitePlugin[])[0];
  }

  it('does nothing unless nuxt dev runs', async () => {
    assert.equal(await plugin(await nuxtRepo(), false), undefined);
  });

  it('sends every import of an adopted component to its wrapper, and the wrapper’s own to the component', async () => {
    const repo = await nuxtRepo();
    const found = (await plugin(repo))!;
    assert.equal(found.enforce, 'pre');
    const real = (file: string) =>
      path
        .join(repo, ...file.split('/'))
        .split(path.sep)
        .join('/');
    const context = {
      resolve: async (source: string) => ({
        id: source.startsWith('~/') ? real(`app/${source.slice(2)}`) : source
      })
    };
    const wrapper = await found.resolveId.call(
      context,
      '~/components/pricing/Plans.vue',
      real('app/pages/pricing.vue'),
      {}
    );
    assert.equal(wrapper, '\0roughbook-section:app/components/pricing/Plans.vue.js');
    assert.equal(
      found.load(wrapper!),
      [
        `import RoughbookOriginal from "${real('app/components/pricing/Plans.vue')}";`,
        `import { wrap as roughbookWrap } from "${real('rough/context-section.ts')}";`,
        `export * from "${real('app/components/pricing/Plans.vue')}";`,
        'export default roughbookWrap(RoughbookOriginal, [{"key":"pricing/plans","address":"/pricing"}]);'
      ].join('\n')
    );
    assert.equal(
      await found.resolveId.call(context, real('app/components/pricing/Plans.vue'), wrapper!, {}),
      null
    );
    assert.equal(
      await found.resolveId.call(
        context,
        '~/components/pricing/Faq.vue',
        real('app/pages/pricing.vue'),
        {}
      ),
      null
    );
    assert.equal(
      await found.resolveId.call(
        context,
        `${real('app/components/pricing/Plans.vue')}?vue&type=style&index=0`,
        real('app/pages/pricing.vue'),
        {}
      ),
      null
    );
    assert.equal(found.load(real('app/pages/pricing.vue')), null);
  });
});

/** The stand-in Vue: elements as plain objects, provide and inject through a global. */
const FAKE_VUE = `export function h(type, props, children) { return { type, props: props ?? {}, children }; }
export function defineComponent(options) { return options; }
export function inject() { return globalThis.roughbookAround ?? null; }
export function provide(key, value) { globalThis.roughbookProvided = value; }
export function onMounted() {}
`;
const FAKE_IMPORTS = `export function useRequestURL() { return new URL(globalThis.roughbookUrl); }\n`;

type VNode = { type: unknown; props: Record<string, unknown>; children: unknown };
type Setup = (
  props: object,
  context: { attrs: Record<string, unknown>; slots: Record<string, unknown> }
) => (() => VNode) | Promise<() => VNode>;
type Wrap = (
  original: unknown,
  sections: { key: string; address: string | null }[]
) => {
  name: string;
  inheritAttrs: boolean;
  setup: Setup;
};

describe('the wrapper', () => {
  const SECTIONS = [
    { key: 'pricing/plans', address: '/pricing' },
    { key: 'home/plans', address: '/' }
  ];
  const Original = { name: 'Plans' };
  const Fork = { name: 'Fork' };

  async function loaded(): Promise<Wrap> {
    const repo = await nuxtRepo();
    for (const item of contextFiles()) write(repo, item.file, item.content);
    write(
      repo,
      CONTEXT_REGISTRY,
      `export const loaders = {
  "pricing/plans/iteration-01": async () => ({ default: globalThis.roughbookFork }),
  "pricing/plans/iteration-02": async () => { throw new Error("it does not compile"); },
};
`
    );
    (globalThis as Record<string, unknown>).roughbookFork = Fork;
    return (
      await bundled<{ wrap: Wrap }>(repo, CONTEXT_SECTION, {
        vue: FAKE_VUE,
        '#imports': FAKE_IMPORTS
      })
    ).wrap;
  }

  async function render(wrap: Wrap, url: string, attrs: Record<string, unknown> = {}) {
    (globalThis as Record<string, unknown>).roughbookUrl = url;
    const made = wrap(Original, SECTIONS);
    assert.equal(made.inheritAttrs, false);
    return (await made.setup({}, { attrs, slots: {} }))();
  }

  it('marks the app’s own component by the page the request is on, with its props', async () => {
    const wrap = await loaded();
    const marker = await render(wrap, 'http://127.0.0.1:3000/', { plans: 3 });
    assert.equal(marker.type, 'roughbook-section');
    assert.equal(marker.props['data-roughbook-section'], 'home/plans');
    assert.deepEqual(marker.props.style, { display: 'contents' });
    const own = (marker.children as VNode[])[0]!;
    assert.equal(own.type, Original);
    assert.deepEqual(own.props, { plans: 3 });
    const bare = await render(wrap, 'http://localhost:3000/pricing?roughbook-markers=0');
    assert.equal(bare.type, Original);
  });

  it('swaps the iteration in for the request that asks, loaded before it renders, with the same props', async () => {
    const wrap = await loaded();
    const marker = await render(
      wrap,
      'http://localhost:3000/pricing?roughbook-swap=pricing/plans/iteration-01',
      { plans: 3 }
    );
    assert.equal(marker.props['data-roughbook-section'], 'pricing/plans');
    assert.equal(marker.props['data-roughbook-swap'], 'pricing/plans/iteration-01');
    const shown = (marker.children as VNode[])[0]!;
    assert.equal(shown.type, Fork);
    assert.deepEqual(shown.props, { plans: 3 });
    assert.equal((globalThis as Record<string, unknown>).roughbookProvided, 'pricing/plans');

    // One that fails shows why in its place, the page kept, and its marker does not claim the swap.
    const failed = await render(
      wrap,
      'http://localhost:3000/pricing?roughbook-swap=pricing/plans/iteration-02'
    );
    assert.equal(failed.props['data-roughbook-swap'], undefined);
    assert.equal(failed.props['data-roughbook-error'], 'pricing/plans/iteration-02');
    assert.match(
      String((failed.children as VNode[])[0]!.children),
      /pricing\/plans\/iteration-02 failed: it does not compile/
    );

    // An iteration that renders the original shows it, not itself again.
    (globalThis as Record<string, unknown>).roughbookAround = 'pricing/plans';
    try {
      const inner = await render(
        wrap,
        'http://localhost:3000/pricing?roughbook-swap=pricing/plans/iteration-01'
      );
      assert.equal((inner.children as VNode[])[0]!.type, Original);
    } finally {
      delete (globalThis as Record<string, unknown>).roughbookAround;
    }
  });

  it('is the app’s own component, unmarked, for a request from the network', async () => {
    const wrap = await loaded();
    const own = await render(
      wrap,
      'http://192.168.1.37:3000/pricing?roughbook-swap=pricing/plans/iteration-01'
    );
    assert.equal(own.type, Original);
  });

  it('Pick posts the section a click fell in, instead of following the page', () => {
    const section = contextFiles().find(item => item.file === CONTEXT_SECTION)!.content;
    assert.match(section, /get\("roughbook-pick"\) !== "1"/);
    assert.match(section, /event\.preventDefault\(\);/);
    assert.match(section, /closest\("\[data-roughbook-section\]"\)/);
    assert.match(section, /postMessage\(\{ roughbook: "section", key \}, "\*"\)/);
  });
});
